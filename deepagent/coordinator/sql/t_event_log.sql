CREATE TABLE t_event_log (
  event_id BIGINT UNSIGNED NOT NULL COMMENT 'event id generated by id generator and used as cursor',
  namespace VARCHAR(128) NOT NULL COMMENT 'tenant namespace',
  session_id VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'owner session id resolved from thread at write time',
  thread_id BIGINT UNSIGNED NOT NULL COMMENT 'owner thread id',
  in_thread_seq BIGINT NOT NULL DEFAULT 0 COMMENT 'producer-provided sequence within owner thread',
  turn_id VARCHAR(128) NOT NULL COMMENT 'logical turn id, usually triggered by one input message',
  event_type VARCHAR(128) NOT NULL COMMENT 'business-defined event type',
  payload MEDIUMBLOB COMMENT 'opaque business event payload',
  metadata_json TEXT COMMENT 'lightweight extension metadata in json',
  created_at DATETIME(6) NOT NULL COMMENT 'create time',
  PRIMARY KEY (event_id),
  KEY idx_namespace_thread_event (namespace, thread_id, event_id),
  KEY idx_namespace_thread_turn_event (namespace, thread_id, turn_id, event_id),
  KEY idx_namespace_thread_type_event (namespace, thread_id, event_type, event_id),
  KEY idx_namespace_thread_turn_type_event (namespace, thread_id, turn_id, event_type, event_id),
  KEY idx_namespace_session_event (namespace, session_id, event_id),
  KEY idx_namespace_session_created_event (namespace, session_id, created_at, event_id),
  KEY idx_thread_created_seq (thread_id, created_at, in_thread_seq),
  KEY idx_thread_turn_created_seq (thread_id, turn_id, created_at, in_thread_seq)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci ROW_FORMAT=DYNAMIC COMMENT='thread event append-only log table';
