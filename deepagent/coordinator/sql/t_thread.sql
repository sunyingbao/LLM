CREATE TABLE t_thread (
  thread_id BIGINT UNSIGNED NOT NULL COMMENT 'thread id generated by id generator',
  namespace VARCHAR(128) NOT NULL COMMENT 'tenant namespace',
  env VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'lane environment for ppe isolation',
  user_id BIGINT NOT NULL DEFAULT 0 COMMENT 'owner user id, 0 means unknown or system',
  session_id VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'owner session id for streamout aggregation',
  title VARCHAR(512) NOT NULL DEFAULT '' COMMENT 'thread title',
  status VARCHAR(32) NOT NULL COMMENT 'thread status: idle ready running blocked closed',
  status_reason VARCHAR(512) NOT NULL DEFAULT '' COMMENT 'latest status transition reason',
  ready_at DATETIME(6) NULL COMMENT 'time when thread most recently entered ready',
  lease_token VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'current lease token, hidden from ordinary query api',
  lease_deadline_at DATETIME(6) NULL COMMENT 'current lease deadline',
  lease_owner_hint VARCHAR(256) NOT NULL DEFAULT '' COMMENT 'debug hint for current lease holder',
  created_by VARCHAR(256) NOT NULL DEFAULT '' COMMENT 'creator identity',
  metadata_json TEXT COMMENT 'lightweight extension metadata in json',
  profile TEXT COMMENT 'thread profile in json',
  last_active_at DATETIME(6) NOT NULL COMMENT 'last user or worker activity time',
  created_at DATETIME(6) NOT NULL COMMENT 'create time',
  updated_at DATETIME(6) NOT NULL COMMENT 'update time',
  closed_at DATETIME(6) NULL COMMENT 'close time when thread enters closed',
  PRIMARY KEY (thread_id),
  KEY idx_namespace_session_thread (namespace, session_id, thread_id),
  KEY idx_namespace_user_created (namespace, user_id, created_at, thread_id),
  KEY idx_namespace_env_user_created (namespace, env, user_id, created_at, thread_id),
  KEY idx_namespace_user_active (namespace, user_id, last_active_at, thread_id),
  KEY idx_namespace_env_user_active (namespace, env, user_id, last_active_at, thread_id),
  KEY idx_namespace_ready_scan (namespace, env, status, ready_at),
  KEY idx_namespace_lease_scan (namespace, env, status, lease_deadline_at),
  KEY idx_lease_timeout (status, lease_deadline_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci ROW_FORMAT=DYNAMIC COMMENT='thread state and lease source-of-truth table';
