CREATE TABLE t_memory_source (
  id BIGINT NOT NULL COMMENT 'database row id generated by caller-provided id generator',
  user_id VARCHAR(128) NOT NULL COMMENT 'memory owner user id',
  source_thread_id VARCHAR(128) NOT NULL COMMENT 'source Agent Coordinator thread id',
  source_updated_at DATETIME(6) DEFAULT NULL COMMENT 'latest source thread update time used for stage1 eligibility',
  eligible_at DATETIME(6) DEFAULT NULL COMMENT 'earliest time this source may be claimed by stage1',
  mode VARCHAR(32) NOT NULL DEFAULT 'enabled' COMMENT 'source memory mode: enabled disabled polluted',
  status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT 'stage1 source status',
  last_stage1_success_source_updated_at DATETIME(6) DEFAULT NULL COMMENT 'source watermark processed by last successful stage1',
  lease_until DATETIME(6) DEFAULT NULL COMMENT 'stage1 lease expiry',
  owner VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'stage1 lease owner',
  ownership_token VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'stage1 lease token',
  attempts INT NOT NULL DEFAULT 0 COMMENT 'stage1 claim attempts',
  last_stage1_output_key VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'last logical stage1 output key',
  error_summary TEXT COMMENT 'latest stage1 error summary',
  updated_at DATETIME(6) DEFAULT NULL COMMENT 'row update time',
  PRIMARY KEY (id),
  UNIQUE KEY uniq_user_source (user_id, source_thread_id),
  KEY idx_stage1_claim (mode, eligible_at, lease_until),
  KEY idx_user_updated (user_id, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci ROW_FORMAT=DYNAMIC COMMENT='AIC Agent SDK worker memory stage1 source candidates';
